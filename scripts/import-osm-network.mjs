#!/usr/bin/env node
/**
 * Harvest a walking network from OpenStreetMap into a committed dataset.
 *
 *   npm run osm:network                      # the Université de Yaoundé I campus
 *   npm run osm:network -- --bbox 3.85,11.49,3.87,11.51 --out custom.json
 *
 * Why this is a script and not a seeder: the harvest needs the public internet, seeding must not.
 * The output is committed alongside the other campus datasets so `db:seed` stays offline,
 * reproducible and reviewable — a diff shows exactly which paths changed and when.
 *
 * Run it from a machine with network access. It is deliberately conservative with Overpass:
 * one request, a long timeout, and a clear error if the public instance is busy.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildWalkingGraph, overpassQuery } from './osm-network.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const DATA_DIR = join(root, 'backend', 'database', 'data');
const ENDPOINT = process.env.OVERPASS_URL ?? 'https://overpass-api.de/api/interpreter';

/** Université de Yaoundé I campus and the streets immediately around it. */
const DEFAULT_BBOX = { minLat: 3.8515, minLng: 11.4940, maxLat: 3.8620, maxLng: 11.5055 };

function parseArgs(argv) {
  const args = { bbox: DEFAULT_BBOX, out: 'yaounde-uy1-walking-network.json' };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--bbox') {
      const parts = String(argv[++i] ?? '').split(',').map(Number);
      if (parts.length !== 4 || parts.some((n) => !Number.isFinite(n))) {
        throw new Error('--bbox needs minLat,minLng,maxLat,maxLng');
      }
      args.bbox = { minLat: parts[0], minLng: parts[1], maxLat: parts[2], maxLng: parts[3] };
    } else if (argv[i] === '--out') {
      args.out = String(argv[++i] ?? '');
    }
  }
  return args;
}

async function main() {
  const { bbox, out } = parseArgs(process.argv.slice(2));
  const query = overpassQuery(bbox);

  console.log(`[osm] ${ENDPOINT}`);
  console.log(`[osm] bbox ${bbox.minLat},${bbox.minLng},${bbox.maxLat},${bbox.maxLng}`);

  let response;
  try {
    response = await fetch(ENDPOINT, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/x-www-form-urlencoded',
        'User-Agent': 'CampusFlow/1.0 (campus walking graph import)',
      },
      body: new URLSearchParams({ data: query }),
    });
  } catch (cause) {
    // Distinguish "this machine has no internet" from "Overpass said no". The first is the common
    // case in a sandbox or CI container and has nothing to do with the query.
    throw new Error(
      `Could not reach ${ENDPOINT} (${cause.message}). This importer needs outbound internet ` +
        'access; run it from a machine that has it, or set OVERPASS_URL to a reachable mirror.',
    );
  }

  const text = await response.text();

  if (!response.ok || text.trimStart().startsWith('<')) {
    throw new Error(
      `Overpass returned ${response.status}. The public instance throttles heavy queries; ` +
        `wait a minute and retry, or set OVERPASS_URL to another mirror.\n${text.slice(0, 400)}`,
    );
  }

  let payload;
  try {
    payload = JSON.parse(text);
  } catch {
    throw new Error(`Overpass did not return JSON (it is usually busy):\n${text.slice(0, 400)}`);
  }

  const elements = payload.elements ?? [];
  const { nodes, edges, skipped } = buildWalkingGraph(elements);

  if (edges.length === 0) {
    throw new Error('No walkable ways in that bounding box — refusing to write an empty network.');
  }

  const totalMetres = edges.reduce((sum, edge) => sum + edge.weight, 0);

  const dataset = {
    schema_version: 1,
    source: {
      provider: 'OpenStreetMap',
      licence: 'ODbL 1.0',
      attribution: '© OpenStreetMap contributors — data made available under the Open Database License (ODbL).',
      licence_url: 'https://www.openstreetmap.org/copyright',
      harvested_at: new Date().toISOString().slice(0, 10),
      osm_base_timestamp: payload.osm3s?.timestamp_osm_base ?? null,
      endpoint: ENDPOINT,
      query,
      notes: [
        'Generated by scripts/import-osm-network.mjs — do not hand-edit; re-run the importer.',
        'Ways are split at shared nodes so each edge runs junction to junction; the intermediate shape is kept in `geometry` as [lng, lat].',
        'Edges are bidirectional: `oneway` constrains vehicles, and this graph routes people on foot.',
        'Steps are imported as edge_type=stairwell with accessible=false so step-free routing can avoid them.',
        'Motorways and trunk roads are excluded: routing a student along one is a safety problem, not an inefficiency.',
      ],
    },
    bbox,
    stats: {
      ways_in_extract: elements.filter((e) => e.type === 'way').length,
      ways_skipped_not_walkable: skipped,
      nodes: nodes.length,
      edges: edges.length,
      total_path_metres: Math.round(totalMetres),
      accessible_edges: edges.filter((e) => e.accessible).length,
    },
    nodes,
    edges,
  };

  mkdirSync(DATA_DIR, { recursive: true });
  const target = resolve(DATA_DIR, out);
  writeFileSync(target, `${JSON.stringify(dataset, null, 2)}\n`);

  console.log(`[osm] ${dataset.stats.nodes} nodes · ${dataset.stats.edges} edges · ` +
    `${dataset.stats.total_path_metres} m · ${skipped} non-walkable ways skipped`);
  console.log(`[osm] wrote ${target}`);
  console.log('[osm] next: php backend/artisan db:seed');
}

main().catch((error) => {
  console.error(`[osm] ${error.message}`);
  process.exit(1);
});
